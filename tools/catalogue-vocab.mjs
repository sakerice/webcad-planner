//
// 「どの浴槽が合うか」を選ばせても、**選択肢が全部間違っていれば正しい家に
// ならない**。ここは、その手前で気づくための表である。
//
// 出どころ: 住宅設備メーカーの標準寸法（1坪UB・間口2550のシステムキッチン・
