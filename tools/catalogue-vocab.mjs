/** その品が、日本の住宅の寸法に収まっているか。 */
export function realSizeOk(kind, w, d) {
  const spec = REAL_SIZE[kind];
  if (!spec) return null;
  const width = Number(w), depth = Number(d);
  if (!Number.isFinite(width) || !Number.isFinite(depth)) return false;
  // 向きはどちらでもよい（幅と奥行が入れ替わって登録されている品がある）。
  const fits = (a, b) => a >= spec.w[0] && a <= spec.w[1] && b >= spec.d[0] && b <= spec.d[1];
  return fits(width, depth) || fits(depth, width);
}
