/** kind と高さが噛み合っているか。合わないものだけ理由を返す。 */
export function heightProblem(kind, h) {
  const range = HEIGHT_RULES[kind];
  const height = Number(h);
  if (!range || !Number.isFinite(height) || height <= 0) return null;
  if (height >= range[0] && height <= range[1]) return null;
  return `${KINDS[kind].ja} としては高さ ${Math.round(height)}mm が範囲外（${range[0]}〜${range[1]}mm）`;
}

// 日本の住宅で実際に使われている寸法。幅×奥行の mm。
//
// なぜ在るのか
// ------------
// 点数が足りていても、**寸法が合っていなければ家にならない**。
// 実際、浴槽と名の付く12点を測ったところ、いちばん大きいもので 1307×681
// だった。1坪ユニットバス(1820角)に入る湯船は 1600×750 で、カタログには
