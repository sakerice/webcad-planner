// 高さから決まる種別。**これは計算できるので、モデルに聞かない。**
// 「fmp-Table34 は h629 のローテーブルで机ではない」という取り違えは、
// kind と高さを突き合わせれば機械で拾える。
// 実物の寸法で引いてある。日本の住宅で使われている値:
//   座卓・リビングテーブル  350〜450    ダイニング  700〜720
//   学習机・書斎机         700〜780    カウンター  850〜1100
//
// **間を広く取らない。** 広く取ると、どちらでもない高さの品が黙って通る。
// 実際、furniture_mega のテーブル50点のうち36点が h616〜631 に固まっている
// （うち16点がぴったり629）。これは座卓にも食卓にも高さが合っていない。
// 範囲を 640 まで広げるとこの36点が「ローテーブル」として通ってしまうので、
// 560 で切って要確認に落とす。docs/quality-team.md が挙げている
// 「fmp-Table34 は h629 のローテーブルで机ではない」は、この山の一部である。
