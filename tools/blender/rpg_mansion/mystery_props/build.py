def fallen_glass():
    g=glass('Glass wine glass','#dfe8ea',.42)
    parts=[lathe('Wine glass foot',[(.014,0),(.026,.002),(.025,.004),(.006,.006)],g,48),
           cylinder('Wine glass stem',(0,0,.040),.0035,.070,g,sides=24)]
    profile=[(.008,.074),(.025,.103),(.034,.150),(.031,.150),(.022,.105),(.006,.080)]
    # Capped break surfaces keep the broken bowl a watertight solid.
    steps=44;verts=[]
    for r,z in profile:
        for i in range(steps+1):
            a=math.radians(32+296*i/steps);verts.append((r*math.cos(a),r*math.sin(a),z))
    faces=[];n=steps+1
    for k in range(len(profile)):
        nxt=(k+1)%len(profile)
        for i in range(steps):faces.append((k*n+i,k*n+i+1,nxt*n+i+1,nxt*n+i))
    faces.extend([tuple(k*n for k in reversed(range(len(profile)))),tuple(k*n+steps for k in range(len(profile)))])
    parts.append(mesh('Broken open glass bowl',verts,faces,g))
    for o in parts:
        for v in o.data.vertices:v.co=Matrix.Rotation(math.pi/2,4,'Y')@v.co+Vector((-.11,0,.034))
    for i,(x,y) in enumerate([(.084,.048),(.105,-.018),(.125,.022)]):
        parts.append(polygon('Small glass shard',[(x-.014,y-.010),(x+.016,y-.004),(x+.006,y+.017)],.001,.0035,g))
    return finish(parts,(250,150,68))


def bottle():
    g=glass('Glass amber bottle','#a96e27',.52)
    cork=mat('Natural cork','#997446',rough=.9)
    paper=mat('Blank paper label','#ded7bd',rough=.86)
    parts=[lathe('Amber glass bottle',[(.020,0),(.024,.005),(.025,.017),(.025,.083),
           (.023,.092),(.011,.104),(.010,.114),(.007,.114),(.007,.104),(.020,.084),(.020,.006)],g,48),
           cylinder('Cork stopper',(0,0,.112),.008,.016,cork,sides=24)]
    # A curved, blank label on -Y; no text, brand, contents, or secret information.
    verts=[];steps=16
    for r in (.0252,.0256):
        for z in (.036,.071):
            for i in range(steps+1):
                a=math.radians(230+80*i/steps);verts.append((r*math.cos(a),r*math.sin(a),z))
    n=steps+1;faces=[]
    for i in range(steps):
        faces.extend([(i,i+1,n+i+1,n+i),(2*n+i,3*n+i,3*n+i+1,2*n+i+1),
                      (i,2*n+i,2*n+i+1,i+1),(n+i,n+i+1,3*n+i+1,3*n+i)])
    faces.extend([(0,n,3*n,2*n),(steps,2*n+steps,3*n+steps,n+steps)])
    parts.append(mesh('Blank curved label',verts,faces,paper))
    return finish(parts,(50,50,120))


