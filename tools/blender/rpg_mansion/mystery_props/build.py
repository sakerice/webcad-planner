def mat(name,colour,channel=None,rough=.5,metallic=0):
    m=matp(name,colour,rough=rough,metal=metallic)
    if channel:m['finishChannel']=channel
    return m


def glass(name='Glass',colour='#dfe8ea',alpha=.42):
    m=mat(name,colour,rough=.12)
    b=m.node_tree.nodes.get('Principled BSDF')
    rgba=list(b.inputs['Base Color'].default_value);rgba[3]=alpha
    b.inputs['Base Color'].default_value=rgba;b.inputs['Alpha'].default_value=alpha
    b.inputs['Transmission Weight'].default_value=.80
    b.inputs['IOR'].default_value=1.46
    m.surface_render_method='DITHERED';m.use_transparency_overlap=False
    return m


def mesh(name,verts,faces,material):
    data=bpy.data.meshes.new(name);data.from_pydata(verts,[],faces);data.update()
    o=bpy.data.objects.new(name,data);bpy.context.collection.objects.link(o)
    data.materials.append(material)
    return o


def polygon(name,points,z0,z1,material):
    n=len(points)
    verts=[(x,y,z) for z in (z0,z1) for x,y in points]
    faces=[tuple(reversed(range(n))),tuple(range(n,2*n))]
    for i in range(n):
        j=(i+1)%n;faces.append((i,j,n+j,n+i))
    return mesh(name,verts,faces,material)


def lathe(name,profile,material,sides=48,notches=False):
    rings=[]
    for r,z in profile:
        points=[]
        for i in range(sides):
            a=math.tau*i/sides
            # Four real rim depressions; the basin floor remains intact.
            cut=.006*max(0,math.cos(a*4))**12 if notches and z>.024 else 0
            points.append((r*math.cos(a),r*math.sin(a),z-cut))
        rings.append(points)
    return kit.shell(name,rings,[material],[0]*(len(rings)-1))


def pipe(name,points,radius,material,closed=False,sides=8,flatten=1):
    curve=bpy.data.curves.new(name,'CURVE');curve.dimensions='3D';curve.resolution_u=1
    curve.bevel_depth=radius;curve.bevel_resolution=1;curve.use_fill_caps=True
    spline=curve.splines.new('POLY');spline.points.add(len(points)-1)
    for p,co in zip(spline.points,points):p.co=(*co,1)
    spline.use_cyclic_u=closed
    o=bpy.data.objects.new(name,curve);bpy.context.collection.objects.link(o)
    curve.materials.append(material);kit.activate(o);bpy.ops.object.convert(target='MESH')
    o=bpy.context.object
    if flatten!=1:
        for v in o.data.vertices:v.co.z*=flatten
    return o


def torus(name,center,major,minor,material,rotation=(0,0,0),segments=24):
    bpy.ops.mesh.primitive_torus_add(major_segments=segments,minor_segments=6,
        location=center,rotation=rotation,major_radius=major,minor_radius=minor)
    o=bpy.context.object;o.name=name;bpy.ops.object.transform_apply(location=True,rotation=True,scale=True)
    o.data.materials.append(material)
    for p in o.data.polygons:p.use_smooth=True
    return o


def text(name,body,position,xaxis,yaxis,size,material,depth=.00015):
    curve=bpy.data.curves.new(name,'FONT');curve.body=body;curve.size=size
    curve.align_x='CENTER';curve.align_y='CENTER';curve.extrude=depth;curve.resolution_u=2
    o=bpy.data.objects.new(name,curve);bpy.context.collection.objects.link(o);curve.materials.append(material)
    kit.activate(o);bpy.ops.object.convert(target='MESH');o=bpy.context.object
    x=Vector(xaxis);y=Vector(yaxis);z=x.cross(y);origin=Vector(position)
    for v in o.data.vertices:v.co=origin+x*v.co.x+y*v.co.y+z*v.co.z
    return o


def finish(parts,size):
    # Keep independent closed shells separate while joining their material slots.
    for o in parts:
        bm=bmesh.new();bm.from_mesh(o.data)
        bmesh.ops.remove_doubles(bm,verts=list(bm.verts),dist=1e-8)
        bmesh.ops.dissolve_degenerate(bm,edges=list(bm.edges),dist=1e-8)
        bmesh.ops.triangulate(bm,faces=list(bm.faces));bmesh.ops.recalc_face_normals(bm,faces=list(bm.faces))
        assert all(e.is_manifold for e in bm.edges),o.name
        bm.to_mesh(o.data);bm.free();o.data.update()
    obj=combine(parts)
    pts=[obj.matrix_world @ v.co for v in obj.data.vertices]
    lo=[min(p[i] for p in pts) for i in range(3)];hi=[max(p[i] for p in pts) for i in range(3)]
    for v in obj.data.vertices:
        v.co.x=(v.co.x-(lo[0]+hi[0])/2)*size[0]/1000/(hi[0]-lo[0])
        v.co.y=(v.co.y-(lo[1]+hi[1])/2)*size[1]/1000/(hi[1]-lo[1])
        v.co.z=(v.co.z-lo[2])*size[2]/1000/(hi[2]-lo[2])
    obj.data.update()
    obj['front']='+Z';obj['originalProceduralAsset']=True;obj['bloodlessGameProp']=True
    return obj


def chalk():
    chalk=mat('White chalk','#e8e5dc',rough=.97)
    # Generic human outline; neither a corpse nor a depiction of an injury.
    outline=[(-.07,.64),(-.17,.59),(-.28,.44),(-.47,.37),(-.59,.12),(-.54,.03),
             (-.39,.18),(-.25,.24),(-.18,.07),(-.20,-.06),(-.24,-.71),(-.40,-.82),
             (-.40,-.90),(-.22,-.86),(-.14,-.78),(-.02,-.32),(.14,-.80),(.20,-.91),
             (.36,-.88),(.30,-.78),(.22,-.05),(.19,.12),(.26,.27),(.49,.36),
             (.53,.65),(.47,.69),(.42,.50),(.33,.42),(.19,.58),(.10,.64)]
    # Tube cross-section is flattened to 3mm; all of it sits above the floor.
    # Fit the centre-line before adding the 12mm stroke, so its cross-section
    # is not squeezed merely to fit a nominal adult outline footprint.
    def place(x,y):return ((x+.03)*.938/1.12,(y+.034)*1.838/1.752,.007)
    body=pipe('Chalk body outline',[place(x,y) for x,y in outline],.006, chalk,True,flatten=.25)
    head=pipe('Chalk head outline',[place(.025+.096*math.cos(a),.742+.10*math.sin(a))
                                  for a in [math.tau*i/40 for i in range(40)]],.006,chalk,True,flatten=.25)
    return finish([body,head],(950,1850,3))


