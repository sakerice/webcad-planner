// AI に渡す文の決まり(入力の扱い)。チャット・読み取り・外の AI(MCP)の3つの道で使う。
//
// なぜ在るのか
// ------------
// AI には、利用者の文、プランの中の文字(部屋や物の名前)、道具の結果、図面の中の文字が届く。共有のプランは
// URL を知る誰でも書き換えられ、図面は他人が作った物もある。そこに「前の指示を無視して…」のような文や、
// コード・SQL が紛れても、AI が指示として扱わないようにする。
//
// 形(利用者が決めた設計):
//   - 信頼できない文は、種類ごとの囲み(<user_request> など。assets/js/chat/plan-summary.js の TAGS)に入れて渡す。
//     囲む前に掃除し、囲みを偽って外へ出られないようにする(同じファイルの clean・cleanText)
//   - 決まりは囲みの外の、前の側(system の先頭、MCP の返す文の先頭)に置く
//   - 利用者の依頼の囲み(<user_request>・<user_hint>)の中は「間取りについての依頼・説明」として扱ってよいが、
//     決まりを変える力は無い。プランの要約・道具の結果・名前などの囲みの中は、依頼ですらなくただのデータ
//   - 「記号・コードを無視する」は、実行も解釈もしないという意味。寸法や単位(6畳、2.5m×3m、3640mm)は今までどおり読む
//
// 決まりは固定の文にし、会話ごとに変わる値を混ぜない(プロンプトキャッシュが効くように、毎回同じ位置に同じ文)。
