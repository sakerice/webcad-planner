// 自分の答えを見直させるときの指示文。
//
// なぜ在るのか
// ------------
// 読み取りは1回投げて1回答えを受け取るだけで、**モデルは自分の答えが間取りと
// してどう見えるかを一度も見ていなかった**。手順の最後に検算を置いてはいるが、
// あれは数字の上での確かめで、置いた結果の絵ではない。
//
// ここでは、こちらで描いた絵（assets/js/plan-review-draw.js）を元の図面と
// 並べて渡し、**違っているところを自分で直してもらう**。
//
// 何を直すかはこちらで列挙しない。決め打ちの検査項目を並べると、挙げた項目しか
// 見なくなる。伝えるのは、見比べる相手と、直した結果を返す形だけ。
//
// **直し方も任せる。** 「違っているところを直す」と書くと差分を当てる方向に
// 寄り、部屋を長方形に分け直す・階段を分割して廻りを挟むといった作り直しに
// 近い修正を、やりすぎと判断して控える余地が残る。仕様書は渡しているのだから、
// **それが「このアプリでできることの全部」だと名指しし**、その範囲で元の図面に
// 近いほうを選ばせる。仕様書は形式の決まりであると同時に、使ってよい道具の
// 一覧でもある。
export const REVISE_SYSTEM = [
  "あなたは日本の住宅の間取り図を読み取り、住宅設計アプリが読み込めるJSONデータに変換する専門家です。",
  "自分が変換したJSONを図面と見比べ、このアプリでできることの範囲で作り直します。出力はJSONだけで説明文や前置きは書きません。",
].join("\n");

export function buildRevisePrompt({ json, hint } = {}) {
  return `さきほどあなたがこの図面から作ったJSONを、見直してください。

**1枚目の画像**は、元の間取り図です。
**2枚目の画像**は、あなたが作ったJSONを、そのまま平面図として描き直したものです。
部屋は長方形と室名、置いた物は種類の名前と向きで描いてあります。上辺と左辺の
数字は、あなたが答えた width と depth です。

あなたが作ったJSON:

${json}

2枚の画像を見比べて、**元の間取り図に合うように作り直したJSONを出力して
ください。**

**直し方はあなたが決めてください。** 一緒に渡してある仕様書が、このアプリで
できることのすべてです。その範囲であれば何をしても構いません——部屋を長方形に
分け直す、部屋の区切りを引き直す、物を足す・外す・向きを変える、寸法を読み
直す、どれでも。少しだけ直すことにこだわらず、**元の図面に近いほうを選んで
ください。**

直すところが無ければ、同じJSONをそのまま出力してください。

出力は全体を作り直した完全なJSONとし、差分では書きません。${hint ? `\n\n利用者からの補足: ${hint}` : ""}`;
}
