// house-planner mobile の取り込みデータ仕様。
//
// このファイルが持つもの
// ----------------------
// **仕様だけ。** データの構成、項目、単位、値の決まり。
// 注意喚起・読み取りのコツ・解釈の方針は書かない。それらは手順の側
// (worker/plan-prompt.mjs) に置く。混ぜると、仕様として参照したいときに
// どれが決まりでどれが助言か分からなくなる。
//
// 物の種類と既定寸法は worker/plan-item-spec.mjs から作る。アプリの
// 定数(assets/js/app-constants.js の ISIZES)が正で、書き写すと黙って古くなる。
import { itemTypeTable } from "./plan-item-spec.mjs";

export function planSpec() {
  return `# house-planner mobile 取り込みデータ仕様

## 単位

- 長さ: ミリメートル
- 角度: 度。時計回りを正とする

## 座標系

- x は右が正、y は下が正
- 原点 (0,0) は建物の左上の外角
- 全階で同一の座標系を使う

## 全体の構成

    {
      "floors": [ 階, ... ],
      "notes":  [ 文字列, ... ]
    }

notes は、図から読み取れなかった箇所、および他の記載から判断した箇所を
1件1行で記す。

## 階

    {
      "floor": 整数,
      "width": 数値,
      "depth": 数値,
      "dims":  寸法線,
      "rooms": [ 部屋, ... ],
      "items": [ 物, ... ]
    }

| 項目 | 内容 |
|---|---|
| floor | 階数。1階は 1、2階は 2 |
| width | 建物の総幅 |
| depth | 建物の総奥行き |
| dims | その階の寸法線 |
| rooms | その階の部屋 |
| items | その階の建具・階段・設備 |

## 寸法線 (dims)

    {
      "top":    { "total": 数値, "parts": [ 数値, ... ] },
      "bottom": { "total": 数値, "parts": [ 数値, ... ] },
      "left":   { "total": 数値, "parts": [ 数値, ... ] },
      "right":  { "total": 数値, "parts": [ 数値, ... ] }
    }

| 項目 | 内容 |
|---|---|
| top / bottom / left / right | 建物の上辺・下辺・左辺・右辺 |
| total | その辺の総寸法 |
| parts | 内訳。上辺・下辺は左から、左辺・右辺は上から並べる |

寸法線の数値は壁の芯から芯までの長さを指す。

## 部屋 (rooms)

    {
      "name":  文字列,
      "parts": [ { "x0": 数値, "y0": 数値, "x1": 数値, "y1": 数値 }, ... ]
    }

| 項目 | 内容 |
|---|---|
| name | 室名 |
| parts | その部屋が占める長方形。x0 < x1、y0 < y1 |

1つの部屋は複数の長方形で表せる。同じ部屋に属する長方形の間に壁は生成されない。
部屋どうしは重ならない。

## 物 (items)

    { "type": 文字列, "x": 数値, "y": 数値, "w": 数値, "d": 数値, "rot": 数値 }

| 項目 | 内容 |
|---|---|
| type | 種類 |
| x, y | その物の中心の座標 |
| w | 幅 |
| d | 奥行き |
| rot | 回転角 |

建具（窓・扉）は最も近い壁に取り付けられ、向きはその壁から決まる。

物は部屋と重なってよい。階段の下がトイレや収納になっている場合、その部屋の上に
階段を置く。

### type に使える値

${itemTypeTable()}

既定は、アプリのカタログにある品物の寸法。

| 種類 | w と d |
|---|---|
| 設備（bath / toilet / sink / kitchen） | 既定の値を用いる |
| 階段（stair / stair-corner） | w は既定の値。d は段数に応じて図から読み取った長さ |
| balcony | 図から読み取った寸法を用いる |
| 建具（window / window-door / door-swing / door-slide-s / door-fold / door-opening / door-front） | 図から読み取った寸法を用いる |

## 図面に描かれていた印 (marks)

家具などの印。**items とは別のもの。**

items は「実際に置く物」で、動かせる家具は入れない（図面の家具はメーカーの
標準仕様の絵であって、置く物ではない）。marks はその判断を変えずに、
**図面に何が描かれていたか**だけを残すためにある。

**種類は当てない。見たままを返す。**

| 項目 | 中身 |
|---|---|
| x, y, w, d | 位置と大きさ |
| label | その印に添えられた文字。「TV」「クローゼット」「WIC」など。無ければ空 |
| looks | 見たままの形。「細長い薄い矩形」「円と矩形」「弧のある矩形」など |

当てないのは、判断に要るものが分かれているため。**絵が見えているのはあなた、
日本の住宅の作法（カーテンは窓に付き、幅は窓より左右100〜200mm大きい、など）を
持っているのはこちら。**両方を足して初めて何であるかが決まる。

## アプリが生成する要素

次の要素はこのデータに含めない。読み取った内容から生成される。

| 要素 | 生成元 |
|---|---|
| 壁 | 部屋と部屋の境目、および部屋と屋外の境目 |
| 基礎 | 1階の部屋の外形 |
| 屋根 | 最上階の部屋の外形に軒の出 450mm を加えたもの |
`;
}
