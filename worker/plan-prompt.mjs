// 分けてある。検査もこのファイルだけを読む。
//
// 何を読ませて、何を読ませないか
// ------------------------------
// 読ませるのは **壁・部屋・開口・階段** まで。家具は読ませない。
// 図面の家具記号は「そのメーカーの標準仕様の絵」であって、実際に置く物とは
// 別物だし、アプリには家具のカタログがある。無理に読ませると、量が増えて
// 高くなるうえ、肝心の壁の精度が落ちる。
//
// 座標の約束はアプリと同じ。単位はミリメートル、xは右、yは下が正。
// 壁は芯線(中心線)の線分で、部屋は軸に沿った長方形。

